"""PlatformIO pre-build hook: compile app/index.html into the firmware binary.

Why: the board serves one page and there is no internet on its network, so the app is a
single self-contained file. Putting it on a LittleFS image would mean a second upload step
(`pio run -t uploadfs`) that is easy to forget and whose symptom is "my change did nothing".
Embedding it as a PROGMEM string means one `pio run -t upload` and no way to ship a stale
app.

The source of truth is app/index.html at the repository root level, because the course
reserves the root index.html for the project website (SPEC.md section 8). This script only
generates; it never edits the source.

Two behaviours that matter:
  * It FAILS the build loudly if the app is missing or unquotable, rather than leaving a
    stale header in place and letting the board serve yesterday's app.
  * It only rewrites the header when the content actually changed. Touching it every build
    would make every build a full rebuild.
"""
import sys
from pathlib import Path

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

# A raw-string delimiter unlikely to appear in HTML. We check anyway: if the app ever
# contained the closing sequence, the generated C++ would end the literal early and fail to
# compile somewhere confusing.
DELIM = "MORSEAPP"
CLOSING = ")" + DELIM + '"'

project_dir = Path(env["PROJECT_DIR"])  # noqa: F821
src = project_dir.parent / "app" / "index.html"
dst = project_dir / "include" / "app_html.h"

if not src.is_file():
    sys.exit(
        f"embed_app: {src} not found.\n"
        "            The app is the source of truth for the page the board serves;\n"
        "            without it there is nothing to embed. Build stopped."
    )

html = src.read_text(encoding="utf-8")

if CLOSING in html:
    sys.exit(
        f"embed_app: {src} contains the raw-string delimiter {CLOSING!r}.\n"
        "            That would terminate the C++ literal early. Change the delimiter in\n"
        "            this script, or remove the sequence from the app. Build stopped."
    )

header = (
    "// Generated by scripts/embed_app.py from app/index.html. Do not edit.\n"
    "// Regenerated on every build; git-ignored.\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n"
    "\n"
    f"static const char APP_HTML[] PROGMEM = R\"{DELIM}(\n"
    f"{html}"
    f"){DELIM}\";\n"
)

dst.parent.mkdir(parents=True, exist_ok=True)

# Only write when it changed, so an unchanged app does not force a full rebuild.
if not dst.is_file() or dst.read_text(encoding="utf-8") != header:
    dst.write_text(header, encoding="utf-8")
    print(f"embed_app: {src.name} -> {dst.name} ({len(html)} bytes)")
else:
    print(f"embed_app: {dst.name} already current ({len(html)} bytes)")
